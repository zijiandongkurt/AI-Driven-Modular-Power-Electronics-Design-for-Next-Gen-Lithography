"""
claude_inline_samples.py
========================

52 hand-crafted SPICE netlists for SFT training, one batch per constraint
in pipeline/data/datasets/constraints.json.  Generated by Claude (in
conversation, not via API) with explicit physics calculations:

    Buck:        D = Vout / Vin              ;  t_on = D * period
    Boost:       D = 1 - Vin / Vout          ;  t_on = D * period
    SEPIC (BB):  D = Vout / (Vin + Vout)     ;  t_on = D * period
    Rload     = Vout^2 / Pin

Per constraint, 4 variants:
    - different Vin within the [vin_min, vin_max] range
    - different topology (async / sync / interleaved for buck-only,
      single-stage variants for boost, SEPIC for buck-boost)
    - different L, C, period values for SFT diversity

Run this script once and it writes:
    data/sft/sft_from_claude_inline.jsonl
    pipeline/data/batch_sft_claude_inline_idx<N>/   (canonical layout)
"""

