# ────────────────────────────────────────────────────────────────────────
# Main: write canonical batches + final JSONL, then run validator
# ────────────────────────────────────────────────────────────────────────

def main():
    """Write hand-crafted SFT pairs to disk and run the validator on each batch.

    Reads the ``SAMPLES`` list, groups entries by constraint index, writes
    each group to a canonical ``batch_sft_claude_inline_idx<N>/`` directory,
    runs the validator, and appends passing pairs to
    ``data/sft/sft_from_claude_inline.jsonl``.
    """
    constraints = load_constraints(
        str(REPO_ROOT / "pipeline" / "data" / "datasets" / "constraints.json")
    )
    print(f"[setup] loaded {len(constraints)} constraints")
    print(f"[setup] {len(SAMPLES)} hand-crafted samples to process")

    # Group by idx, write each group as a batch
    by_idx: dict[int, list[dict]] = {}
    for s in SAMPLES:
        by_idx.setdefault(s["idx"], []).append(s)

    all_pairs: list[dict] = []
    for idx, group in sorted(by_idx.items()):
        constraint = constraints[idx]
        batch_id = f"batch_sft_claude_inline_idx{idx}"
        print(f"\n── idx={idx}  vin {constraint.get('vin_min')}-{constraint.get('vin_max')}V "
              f"→ {constraint.get('vout_target')}V, {constraint.get('power_in')}W  "
              f"({len(group)} samples) ──")

        netlists = [g["net"] for g in group]
        written = write_netlists(netlists=netlists, batchID=batch_id)
        print(f"  wrote {len(written)} files")

        # Validate
        val_results = _run_validator(batch_id)
        n_passed = sum(1 for v in val_results.values() if v.get("passed"))
        print(f"  validator: {n_passed}/{len(val_results)} passed")

        # Build SFT pairs for each passing sample
        prompt = make_prompt(constraint)
        for path, sample in zip(written, group):
            info = val_results.get(path.stem) or val_results.get(path.name) or {}
            if not info.get("passed"):
                fail_checks = [k for k, ok in (info.get("checks") or {}).items() if ok is False]
                print(f"  [skip] {sample['tag']}: {fail_checks[:3]}")
                continue
            all_pairs.append({
                "prompt":     prompt,
                "completion": path.read_text(encoding="utf-8"),
                "fitness":    None,
                "source":     f"{batch_id}/{path.stem}",
                "constraint": {k: v for k, v in constraint.items() if not k.startswith("_")},
                "generator":  "claude-inline-handcrafted",
                "tag":        sample["tag"],
            })

    out = REPO_ROOT / "data" / "sft" / "sft_from_claude_inline.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as f:
        for r in all_pairs:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"\n[done] {len(all_pairs)} validator-passing SFT pair(s)")
    print(f"[done] written to {out}")


def _run_validator(batch_id: str) -> dict:
    try:
        from pipeline.netlist_validation.validator import validator
    except ImportError as e:
        print(f"  WARN: validator unavailable ({e})")
        return {}
    val = validator()
    val.validate(batch_id)
    p = REPO_ROOT / "pipeline" / "data" / batch_id / "validation_results.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


if __name__ == "__main__":
    main()
